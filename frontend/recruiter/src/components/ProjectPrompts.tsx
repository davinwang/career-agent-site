import { useEffect, useState } from 'react';
import {
  fetchProjectQuestions,
  fetchResumeQuestions,
  type RecruiterQuestion,
} from '../lib/api';
import type { UiStrings } from '../lib/i18n';
import { CloseIcon } from './Icons';
import { ASK_EVENT, FOCUS_EVENT } from './resume/Projects';

/**
 * Question prompt strip above the chat composer. Three sources, in priority
 * order (only one strip is visible at a time):
 *
 *   1. SHIPPED  — feature prompts bundled with the app (e.g. "upload a JD
 *                 and get a fit assessment"). Always available; shown when
 *                 nothing more specific is active.
 *   2. DOSSIER  — dossier-wide questions generated by the admin agent
 *                 alongside the résumé (`recruiter_questions` in resume data).
 *   3. PROJECT  — per-project questions from source analysis; swap in when
 *                 the recruiter focuses (hover/scroll) a project card.
 *
 * Clicking a question dispatches ASK_EVENT (`direct` = answerable without
 * extra material → send right away; otherwise fill the composer).
 */

const shippedPrompts = (lang: string, t: UiStrings): RecruiterQuestion[] => {
  void lang;
  void t;
  return [
    {
      // Recruiter-perspective phrasing; uploading a JD is a manual step, so
      // needs_input pre-fills the composer instead of sending right away.
      question_zh: '我会提供岗位 JD，请评估候选人与该岗位的匹配度',
      question_en: "I'll provide a job description — assess the candidate's fit for the role",
      needs_input: true,
    },
  ];
};

export function ProjectPrompts({ lang, t }: { lang: string; t: UiStrings }) {
  const [projectQuestions, setProjectQuestions] = useState<Record<string, RecruiterQuestion[]>>({});
  const [resumeQuestions, setResumeQuestions] = useState<RecruiterQuestion[]>([]);
  const [projectName, setProjectName] = useState<string | null>(null);
  const [dismissed, setDismissed] = useState(false);

  useEffect(() => {
    let active = true;
    fetchProjectQuestions().then((q) => {
      if (active) setProjectQuestions(q);
    });
    fetchResumeQuestions().then((q) => {
      if (active) setResumeQuestions(q);
    });
    return () => {
      active = false;
    };
  }, []);

  useEffect(() => {
    const onFocus = (e: Event) => {
      const name = (e as CustomEvent<{ projectName?: string }>).detail?.projectName;
      if (!name) return;
      setProjectName(name);
      setDismissed(false);
    };
    window.addEventListener(FOCUS_EVENT, onFocus);
    return () => window.removeEventListener(FOCUS_EVENT, onFocus);
  }, []);

  const isZh = lang.toLowerCase().startsWith('zh');
  const textOf = (q: RecruiterQuestion) => (isZh ? q.question_zh : q.question_en);

  // Source priority: focused project > dossier-wide > shipped.
  const projectList = projectName
    ? Object.entries(projectQuestions).find(
        ([k]) => projectName.startsWith(k) || k.startsWith(projectName),
      )?.[1] ?? []
    : [];

  let source: 'shipped' | 'dossier' | 'project';
  let list: RecruiterQuestion[];
  if (projectList.length > 0) {
    source = 'project';
    list = projectList;
  } else if (resumeQuestions.length > 0) {
    source = 'dossier';
    list = resumeQuestions;
  } else {
    source = 'shipped';
    list = shippedPrompts(lang, t);
  }

  const visible = dismissed ? [] : list.slice(0, 3);
  if (!visible.length) return null;

  const sourceLabel =
    source === 'project'
      ? `${t.projects.askTitle} · ${projectName}`
      : source === 'dossier'
        ? t.projects.dossierAskTitle
        : t.projects.tryAskTitle;

  const ask = (text: string, direct: boolean) => {
    window.dispatchEvent(new CustomEvent(ASK_EVENT, { detail: { text, direct } }));
  };

  return (
    <div className="relative z-10 shrink-0 border-t border-rule bg-surface/95 px-4 pt-2.5 pb-1 sm:px-5 backdrop-blur-sm">
      <div className="mx-auto w-full max-w-[46rem]">
        <div className="mb-1.5 flex items-center gap-2">
          <span className="min-w-0 flex-1 truncate font-mono text-[9.5px] tracking-[0.16em] text-accent uppercase">
            {sourceLabel}
          </span>
          <button
            type="button"
            onClick={() => setDismissed(true)}
            className="shrink-0 text-mute transition-colors hover:text-accent"
            aria-label={t.chat.close}
          >
            <CloseIcon className="h-3.5 w-3.5" />
          </button>
        </div>
        <div className="flex gap-1.5 overflow-x-auto pb-1.5 [scrollbar-width:none] [&::-webkit-scrollbar]:hidden">
          {visible.map((q, qi) => {
            const text = textOf(q);
            return (
              <button
                key={`${source}-${qi}`}
                type="button"
                onClick={() => ask(text, !q.needs_input)}
                title={q.needs_input ? t.projects.askHint : t.projects.askDirect}
                className="group flex shrink-0 max-w-[280px] items-start gap-1.5 border border-rule bg-raised/60 px-2.5 py-1.5 text-left transition-colors duration-150 hover:border-accent/60"
              >
                <span
                  className={[
                    'mt-[2px] shrink-0 border px-1 py-[1px] font-mono text-[8px] tracking-[0.12em] uppercase',
                    q.needs_input
                      ? 'border-gold/55 bg-goldsoft text-gold'
                      : 'border-teal/45 bg-tealsoft text-teal',
                  ].join(' ')}
                >
                  {q.needs_input ? t.projects.askPrefill : t.projects.askDirect}
                </span>
                <span className="min-w-0 text-[12px] leading-[1.6] text-soft group-hover:text-ink">
                  {text}
                </span>
              </button>
            );
          })}
        </div>
      </div>
    </div>
  );
}

export default ProjectPrompts;
